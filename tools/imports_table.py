#!/usr/bin/env python3
"""Map every import of decompiled/macho/imports.txt to the source file whose import table provides it.

Writes docs/imports.md (symbol -> shim file -> function -> status) and exits 1 if any import is
missing from every table (it would fall back to the logged ml_unimpl thunk at runtime).
Status: 'real' = implemented, 'stub' = intentional no-op/failure (network, IGP, analytics...).

Usage: python3 -I tools/imports_table.py [--check]
"""
import glob, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STUB_FN = re.compile(r'^(stub_\w*|ok|ret0|ret1|ret_obj|audio_fail|aq_unused|g_glNoop|g_glFlush|cg_noop|cg_dummy_ref|cc_CC_MD5|d_net_fail|d_gethostbyname|d_inet_aton|d_SCNetwork\w*|d_atexit|d_sjlj_noop|cf_CFRelease)$')
ENTRY = re.compile(r'\b([FDV])\(\s*([A-Za-z0-9_$]+)\s*(?:,\s*&?([A-Za-z0-9_$]+))?|\{\s*"(_[A-Za-z0-9_$.]+)"\s*,\s*\(uintptr_t\)\s*&?\(?([A-Za-z0-9_$]+)')

table = {}
for path in sorted(glob.glob(os.path.join(ROOT, 'source', '*.c*'))):
    base = os.path.basename(path)
    if base.startswith('._'):
        continue
    src = open(path, encoding='utf-8', errors='replace').read()
    for m in re.finditer(r'const import_entry \w+\[\]\s*=\s*\{(.*?)\n\};', src, re.S):
        body = re.sub(r'//[^\n]*', '', m.group(1))
        for e in ENTRY.finditer(body):
            if e.group(4):
                name, fn, kind = e.group(4), e.group(5), 'data' if body[e.end():e.end() + 8].strip().startswith(', 1') else 'func'
            else:
                name = '_' + e.group(2)
                fn = e.group(3) or e.group(2)
                kind = 'data' if e.group(1) == 'V' else 'func'
            table.setdefault(name, (base, fn, kind))

imports = [l.strip() for l in open(os.path.join(ROOT, 'decompiled', 'macho', 'imports.txt')) if l.strip()]
rows, missing, real, stub = [], [], 0, 0
for imp in imports:
    if imp in table:
        base, fn, kind = table[imp]
        st = 'stub' if STUB_FN.match(fn) else 'real'
        real += st == 'real'
        stub += st == 'stub'
        rows.append(f'| `{imp}` | `{base}` | `{fn}` ({kind}) | {st} |')
    else:
        missing.append(imp)
        rows.append(f'| `{imp}` | -- | `ml_unimpl` thunk | **UNIMPL** (logged) |')

out = os.path.join(ROOT, 'docs', 'imports.md')
with open(out, 'w') as f:
    f.write('# Import table (generated by `tools/imports_table.py`, do not edit by hand)\n\n')
    f.write(f'{len(imports)} imports: **{real} real**, **{stub} stub**, **{len(missing)} unimplemented** '
            '(an unimplemented import resolves to a thunk that logs `unimpl import: <name>` once and returns 0).\n\n')
    f.write('Status: `real` = working shim; `stub` = deliberate no-op / "unavailable" answer '
            '(network, reachability, IGP store UI).\n\n')
    f.write('| Symbol | Shim file | Function | Status |\n|---|---|---|---|\n')
    f.write('\n'.join(rows) + '\n')
print(f'{len(imports)} imports: {real} real, {stub} stub, {len(missing)} unimplemented -> {out}')
if missing:
    print('UNIMPL:', ' '.join(missing))
sys.exit(1 if missing and '--check' in sys.argv else 0)
